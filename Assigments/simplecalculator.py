x = float(input("Enter a number: "))
y = float(input("Enter another number: "))

def add(x, y):
    return x + y 

def subtract(x, y):
    return x - y

def multiply(x, y):
    return x * y 

def divide(x, y):
    return x / y 

def exponentiate(x, y):
    return x ** y 

def modulus(x, y):
    return x % y 

def floor_division(x, y):
    return x // y 

print(input(add(x, y))) 

print(subtract(x, y)) 

print(multiply(x, y)) 

print(divide(x, y)) 

print(exponentiate(x, y)) 

print(modulus(x, y)) 

print(floor_division(x, y)) 

